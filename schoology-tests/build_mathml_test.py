"""Build a Schoology math import test quiz using MathML only.

Equations are written in LaTeX here and converted to MathML with pandoc,
then inserted into a quiz generated by text2qti (which supplies the QTI
structure Schoology needs). The LaTeX annotation pandoc adds is stripped so
only presentation MathML reaches Schoology.

Usage: python3 -I build_mathml_test.py <output.zip>
Requires: text2qti, pandoc
"""
import os
import re
import subprocess
import sys
import tempfile
import zipfile
from xml.sax.saxutils import escape as xml_escape

# token -> (LaTeX, display mode)
EQUATIONS = {
    # 1. fractions, inline in question and choices
    "MTKAA": (r"K = \frac{1}{2}mv^2", False),
    "MTKAB": (r"5\ \mathrm{J}", False),
    "MTKAC": (r"10\ \mathrm{J}", False),
    "MTKAD": (r"25\ \mathrm{J}", False),
    "MTKAE": (r"50\ \mathrm{J}", False),
    # 2. subscripts and fractions in choices
    "MTKBA": (r"F_g = G\frac{m_1 m_2}{r^2}", False),
    "MTKBB": (r"\frac{1}{4}F_g", False),
    "MTKBC": (r"\frac{1}{2}F_g", False),
    "MTKBD": (r"2F_g", False),
    "MTKBE": (r"4F_g", False),
    # 3. display equation, trig, Greek
    "MTKCA": (r"R = \frac{v_0^2 \sin 2\theta}{g}", True),
    "MTKCB": (r"30^\circ", False),
    "MTKCC": (r"45^\circ", False),
    "MTKCD": (r"60^\circ", False),
    "MTKCE": (r"90^\circ", False),
    # 4. display equation, square root
    "MTKDA": (r"T = 2\pi\sqrt{\frac{L}{g}}", True),
    # 5. simple inline fraction and units
    "MTKEA": (r"v = \frac{d}{t}", False),
    "MTKEB": (r"2\ \mathrm{m/s}", False),
    "MTKEC": (r"5\ \mathrm{m/s}", False),
    "MTKED": (r"20\ \mathrm{m/s}", False),
    "MTKEE": (r"2000\ \mathrm{m/s}", False),
    # 6. vectors and compound units
    "MTKFA": (r"\vec{p} = m\vec{v}", False),
    "MTKFB": (r"\mathrm{kg\cdot m/s}", False),
    "MTKFC": (r"\mathrm{kg\cdot m/s^2}", False),
    "MTKFD": (r"\mathrm{N/m}", False),
    "MTKFE": (r"\mathrm{J\cdot s}", False),
    # 7. stress test: Greek, sci notation, < signs, sums, vectors in choices
    "MTKGA": (r"\Delta x = v_0 t + \tfrac{1}{2} a t^2", False),
    "MTKGB": (r"0 < \theta < 90^\circ", False),
    "MTKGC": (r"h = 6.63 \times 10^{-34}\ \mathrm{J\,s}", False),
    "MTKGD": (r"\vec{F}_{\text{net}} = \sum_i \vec{F}_i", False),
    "MTKGE": (r"\lambda", False),
    "MTKGF": (r"\vec{a}", False),
    "MTKGG": (r"m", False),
    "MTKGH": (r"\vec{F}", False),
}

QUIZ = """\
Quiz title: assessor MathML import test
shuffle answers: false

1. Test 1 (fractions, inline). A 2.0 kg cart moves at 5.0 m/s. Using MTKAA, what is its kinetic energy?
a) MTKAB
b) MTKAC
*c) MTKAD
d) MTKAE

2. Test 2 (subscripts, fractions in choices). Gravity follows MTKBA. If the distance r doubles, the force becomes:
*a) MTKBB
b) MTKBC
c) MTKBD
d) MTKBE

3. Test 3 (display equation, trig, Greek). The range of a projectile on level ground is MTKCA Which launch angle gives the maximum range?
a) MTKCB
*b) MTKCC
c) MTKCD
d) MTKCE

4. Test 4 (display equation, square root). The period of a simple pendulum is MTKDA If the length L is made four times longer, the period:
*a) doubles
b) quadruples
c) halves
d) stays the same

5. Test 5 (simple fraction, units). Speed is MTKEA. A car travels 100 m in 20 s. What is its speed?
a) MTKEB
*b) MTKEC
c) MTKED
d) MTKEE

6. Test 6 (vectors, compound units). Momentum is MTKFA. What is the SI unit of momentum?
*a) MTKFB
b) MTKFC
c) MTKFD
d) MTKFE

7. Test 7 (stress test). Displacement is MTKGA for an angle MTKGB with Planck's constant MTKGC and net force MTKGD. Which of these symbols represent vectors? Select ALL that apply.
[ ] MTKGE
[*] MTKGF
[ ] MTKGG
[*] MTKGH

8. Test 8 (control, no math). This question has no equations. It confirms the import itself worked.
*a) Correct
b) Wrong
"""

def to_mathml(latex, display):
    src = ("$$%s$$" if display else "$%s$") % latex
    out = subprocess.run(["pandoc", "-f", "latex", "-t", "html", "--mathml"],
                         input=src, capture_output=True, text=True, check=True).stdout
    m = re.search(r"<math\b.*?</math>", out, re.S)
    if not m:
        sys.exit("pandoc produced no MathML for: %s" % latex)
    mathml = m.group(0)
    # keep presentation MathML only
    mathml = re.sub(r"<annotation\b.*?</annotation>", "", mathml, flags=re.S)
    mathml = mathml.replace("<semantics>", "").replace("</semantics>", "")
    return mathml

def main(out_zip):
    fragments = {tok: to_mathml(tex, disp) for tok, (tex, disp) in EQUATIONS.items()}
    with tempfile.TemporaryDirectory() as work:
        src = os.path.join(work, "mathml_test.txt")
        with open(src, "w") as f:
            f.write(QUIZ)
        subprocess.run(["text2qti", src], check=True, cwd=work)
        built = os.path.join(work, "mathml_test.zip")

        seen = set()
        with zipfile.ZipFile(built) as zin, zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as zout:
            for info in zin.infolist():
                data = zin.read(info.filename)
                if info.filename.endswith(".xml"):
                    text = data.decode("utf-8")
                    for token, fragment in fragments.items():
                        if token in text:
                            seen.add(token)
                            # question HTML is stored XML-escaped inside <mattext>
                            text = text.replace(token, xml_escape(fragment))
                    data = text.encode("utf-8")
                zout.writestr(info, data)
        missing = set(fragments) - seen
        if missing:
            sys.exit("tokens not found in output: %s" % sorted(missing))
    print("wrote", out_zip)

if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]))
